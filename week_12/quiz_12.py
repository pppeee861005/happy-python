# 製作個人通訊錄系統
# 已知：現有通訊錄字典 contacts(如下)
# 動作：撰寫程式以維護個人通訊錄，功能有：
#       1)添加新的朋友姓名與地址  2)以朋友姓名修改其地址
#       3)以朋友姓名刪除整筆紀錄  4)退出通訊錄系統
# 輸出(舉例)：
#   ---------------我的通訊錄---------------
#   通訊明細：{'王大牛':'忠孝東路四段168號', ...,
#             '孫小丁':'堤頂大道文化街9號'}
#   請選擇要做的操作：【1】添加；【2】修改；【3】删除；【0】退出
#   1
#   新增姓名：John
#   住址：Taipei 101
#   已添加
#   請選擇要做的操作：【1】添加；【2】修改；【3】删除；【0】退出
#   3
#   姓名(請勿寫錯)：孫小丁
#   【警告】需要删除姓名為 孫小丁 的紀錄嗎？
#   回答 Y 或 y (Yes)確認  Y
#   紀錄已删除
#   請選擇要做的操作：【1】添加；【2】修改；【3】删除；【0】退出
#   0
#   通訊明細：{'王大牛':'忠孝東路四段168號', ...,
#             'John':'Taipei 101'}
#   ------------------已退出------------------
#################################################################
contacts = {
    '王大牛': '忠孝東路四段168號', 
    '張小花': '內湖路三段18號',
    '趙石頭': '美村路二段37巷7號', 
    '孫小丁': '堤頂大道文化街9號'
}
def add(contacts):
    """要求輸入並添加新的朋友姓名與地址"""
    name = input("新增姓名：")
    address = input("住址：")
    # 字典新增資料：直接指定 contacts[key] = value
    contacts[name] = address
    print("已添加")
def modify(contacts):
    """要求輸入並以朋友姓名修改其地址"""
    name = input("要修改誰的住址？请输入姓名：")
    # 先檢查這個人是否在通訊錄內
    if name in contacts:
        new_address = input(f"請輸入 {name} 的新住址：")
        # 字典修改資料：與新增相同，若 Key 存在就會直接覆蓋舊值
        contacts[name] = new_address
        print("地址已修改")
    else:
        print(f"【錯誤】通訊錄中找不到姓名為「{name}」的朋友。")
def delete(contacts):
    """要求輸入並以朋友姓名刪除整筆紀錄"""
    name = input("姓名(請勿寫錯)：")
    if name in contacts:
        # 彈出確認警告
        confirm = input(f"【警告】需要刪除姓名為 {name} 的紀錄嗎？\n回答 Y 或 y (Yes)確認：")
        if confirm.lower() == 'y':
            # 字典刪除資料：使用 del 關鍵字
            del contacts[name]
            print("紀錄已刪除")
        else:
            print("已取消刪除")
    else:
        print(f"【錯誤】通訊錄中找不到姓名為「{name}」的朋友。")
# ==========================================
# 主程式執行流程 (無窮迴圈選單)
# ==========================================
if __name__ == "__main__":   
    while True:
        print("-" * 15 + "我的通訊錄" + "-" * 15)
        print(f"通訊明細：{contacts}")
        # 讓使用者選擇功能
        choice = input("請選擇要做的操作：【1】添加；【2】修改；【3】刪除；【0】退出\n")
        if choice == "1":
            add(contacts)
        elif choice == "2":
            modify(contacts)
        elif choice == "3":
            delete(contacts)
        elif choice == "0":
            # 退出系統
            print(f"通訊明細：{contacts}")
            print("-" * 18 + "已退出" + "-" * 18)
            break  # 強制中斷 while 迴圈
        else:
            print("【輸入錯誤】請輸入 1, 2, 3 或 0！\n")

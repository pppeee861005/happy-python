# [練習三]
# 字串解析與擷取
# 問題：有字串如下, 請擷取並印出所有在 '@' 字元後的網域名稱
# 輸入：
#    'From stephen.marquard@uct.ac.za Sat Jan 5 09:14:16 2008 \
#     steve@apple.com brian@ibm.com rocky@google.com Mon Jan 7'
# 輸出：
#    (uct.ac.za, apple.com, ibm.com, google.com)
# (請分別使用 str.find() 與 str.split() 方法撰寫程式)
############################################################################
data = 'From stephen.marquard@uct.ac.za Sat Jan 5 09:14:16 2008 steve@apple.com brian@ibm.com rocky@google.com Mon Jan 7'
domains = []
words = data.split() # 先拆成一個個單字
for word in words:
    if '@' in word:
        # 以 @ 為界拆兩半，取後半部 [1]
        domain = word.split('@')[1]
        domains.append(domain)
print("使用 split 擷取結果：", tuple(domains))

